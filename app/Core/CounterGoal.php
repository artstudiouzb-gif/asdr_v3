<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Путь показателя к цели — для вариантов «Полоса к цели» и «Шкала по годам»
 * блока «Показатели».
 *
 * Число без цели ничего не говорит о том, много это или мало: «68 %» — это
 * почти готово или только треть пути? Поэтому у показателя бывают база
 * (откуда начали) и цель, а доля пройденного считается от базы, а не от
 * нуля: рост с 41 % до 68 % при цели 100 % — это 46 % пути, а не 68 %.
 *
 * Значения набираются как в документе («5,6», «12 400») и разбираются тем же
 * `ChartData::number`, что и у «Диаграммы»: второй разборщик чисел разошёлся
 * бы с первым на первой же запятой. Не разобралось число или цель совпала с
 * базой — пути нет, и шаблон показывает показатель обычным числом: полоса без
 * смысла хуже, чем её отсутствие.
 */
final class CounterGoal
{
    /**
     * Доля пройденного пути в процентах, 0..100, или null, если посчитать
     * нечем. Перевыполнение упирается в 100 — полоса не вылезает за шкалу, а
     * само значение рядом всё равно показывает, насколько цель превышена.
     */
    public static function progress(string $value, string $target, string $base = ''): ?float
    {
        $current = ChartData::number($value);
        $goal = ChartData::number($target);
        if ($current === null || $goal === null) {
            return null;
        }
        $start = trim($base) === '' ? 0.0 : ChartData::number($base);
        if ($start === null || abs($goal - $start) < 1e-9) {
            return null;
        }

        return max(0.0, min(100.0, ($current - $start) / ($goal - $start) * 100));
    }

    /** Доля для CSS: точка вместо запятой и не больше одного знака. */
    public static function css(float $percent): string
    {
        return rtrim(rtrim(number_format($percent, 1, '.', ''), '0'), '.') . '%';
    }
}
