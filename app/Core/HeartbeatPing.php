<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Сигнал наружу: «сайт жив».
 *
 * Свой сторож (`app/Console/watchdog.php`) видит молчащие воркеры, застрявшие
 * очереди и кончающийся диск — но работает он на том же сервере. Если сервер
 * или cron умерли, умер и сторож, и сообщить об этом некому. Единственное, что
 * CMS может сделать со своей собственной смертью, — регулярно доказывать
 * обратное тому, кто снаружи.
 *
 * Отсюда правило: **пингуем только чистый проход**. Тревогу поднимает не наш
 * сигнал, а его отсутствие — так устроен любой сервис-приёмник
 * (healthchecks.io, Better Uptime, cron-мониторы). Отправлять «у меня беда»
 * бессмысленно: в настоящей аварии отправлять будет некому, и приёмник всё
 * равно узнаёт о ней по тишине.
 *
 * Адрес берётся из переменной окружения, а не из настроек в базе: он содержит
 * секретный идентификатор приёмника, задаётся один раз при настройке сервера и
 * лежит там же, где `HEALTH_CHECK_TOKEN`. Настройка в админке дала бы редактору
 * возможность увести сигнал на чужой адрес.
 */
final class HeartbeatPing
{
    /** Ждать дольше нечего: приёмник либо ответил быстро, либо не ответил. */
    private const TIMEOUT = 8;

    public static function url(): string
    {
        return trim((string) getenv('MONITORING_HEARTBEAT_URL'));
    }

    public static function isConfigured(): bool
    {
        return self::url() !== '';
    }

    /**
     * Отправляет сигнал. Возвращает false, если сигнал не настроен или не ушёл.
     *
     * Неудача пинга **не влияет** на работу сторожа: не дозвонились до
     * приёмника — это его тревога, а не наша, и ронять из-за неё проход,
     * который прошёл успешно, нельзя. Запрос идёт через `getSafeRemote`:
     * адрес приходит из окружения, но проверка публичности хоста и закрепление
     * IP стоят дёшево и снимают весь класс SSRF-ошибок при опечатке.
     */
    public static function send(): bool
    {
        $url = self::url();
        if ($url === '') {
            return false;
        }

        try {
            $response = Http::getSafeRemote($url, [], self::TIMEOUT);
            $status = (int) $response['status'];
            if ($status >= 200 && $status < 400) {
                return true;
            }
            $error = (string) $response['error'];
            Logger::warning('Heartbeat: сигнал не принят — ' . ($error !== '' ? $error : 'ответ ' . $status) . '.');
        } catch (\Throwable $e) {
            Logger::warning('Heartbeat: сигнал не ушёл — ' . $e->getMessage());
        }

        return false;
    }
}
