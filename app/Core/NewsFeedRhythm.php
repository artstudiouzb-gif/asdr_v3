<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Ритм ленты новостей: цикл из четырёх рядов — «обложка плюс две компактные»
 * → ряд из четырёх компактных → «две компактные плюс широкая» → ряд из
 * четырёх компактных.
 *
 * Зачем: страница из одинаковых карточек читается как таблица, глазу не за что
 * зацепиться. Крупные карточки разбивают сетку и показывают анонс, который в
 * компактную не помещается.
 *
 * Крупных вида два, и это не украшение, а разные роли. **Обложка** открывает
 * цикл: фотография во всю карточку, текст поверх неё — так выглядит главная
 * новость страницы. **Широкая** замыкает третий ряд: фотография сбоку, текст
 * рядом — ей достаточно веса, чтобы удержать композицию, но она не спорит с
 * обложкой за роль главной. Обе занимают по **две ячейки** сетки.
 *
 * Арифметика: цикл — четырнадцать карточек и шестнадцать ячеек, то есть ровно
 * четыре полных ряда при четырёх колонках и восемь при двух. Крупные стоят в
 * первом и третьем ряду (позиции 0 и 9), поэтому лента идёт зигзагом, а не
 * повторяет одну и ту же строку сверху вниз. Замыкающий ряд компактных
 * карточек отделяет широкую от обложки следующей страницы.
 *
 * А вот на три колонки цикл не раскладывается: крупная карточка рано или
 * поздно упирается в последнюю колонку, где ей не хватает места, сетка
 * переносит её на следующий ряд и оставляет дыру. Поэтому на трёх колонках
 * растяжение выключается в CSS (см. gov-theme.css).
 *
 * Отдельной крупной новости над сеткой нет: первая новость и есть обложка
 * цикла, поэтому у первой страницы нет особой композиции.
 */
final class NewsFeedRhythm
{
    /** Обложка: фотография во всю карточку, текст поверх. */
    public const SLOT_HERO = 'hero';

    /** Широкая: фотография сбоку, текст рядом. */
    public const SLOT_WIDE = 'wide';

    /** Обычная карточка: фотография сверху, текст под ней. */
    public const SLOT_COMPACT = 'compact';

    /** Карточек в цикле: две крупные и двенадцать компактных. */
    public const CYCLE = 14;

    /** Ячеек сетки в цикле: каждая крупная занимает две. */
    public const CELLS_PER_CYCLE = 16;

    /**
     * Места крупных карточек в цикле (индекс с нуля).
     *
     * Ноль — начало первого ряда (обложка слева), девять — конец третьего
     * (широкая справа, после двух компактных). Второй и четвёртый ряды —
     * четыре компактные карточки.
     */
    public const WIDE_POSITIONS = [0 => self::SLOT_HERO, 9 => self::SLOT_WIDE];

    /** Карточек на странице: ровно один полный цикл, четыре ряда. */
    public const PAGE_SIZE = 14;

    /**
     * Вид карточки по её месту в ленте. Индекс — с нуля, в пределах страницы.
     */
    public static function slot(int $index): string
    {
        if ($index < 0) {
            return self::SLOT_COMPACT;
        }

        return self::WIDE_POSITIONS[$index % self::CYCLE] ?? self::SLOT_COMPACT;
    }

    /**
     * Занимает ли карточка две ячейки сетки. Верно для обоих крупных видов:
     * растяжение у них общее, различается только внутреннее устройство.
     */
    public static function isWide(int $index): bool
    {
        return self::slot($index) !== self::SLOT_COMPACT;
    }
}
