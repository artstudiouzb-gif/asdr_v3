<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Пропорции кадра карусели — один список на блок «Слайдер» и на виджет
 * «Фотокарусель». Разметка и стили у них общие, поэтому и набор пропорций
 * обязан быть общим: раздельные списки разъезжаются молча, и в одной форме
 * появляется формат, которого нет в другой.
 *
 * Значения — имена CSS-классов (`.block-slider--ratio-<ключ>`), поэтому ключ
 * пишется через дефис, а не двоеточием.
 */
final class SliderRatio
{
    public const DEFAULT = '16-9';

    /**
     * От самого широкого к вертикальному. Вертикальные форматы нужны не
     * «на всякий случай»: карточки для соцсетей приходят именно в 4:5, 1:1 и
     * 9:16, а при широкой пропорции `object-fit: cover` срезает у них верх и
     * низ — от карточки остаётся полоса по центру.
     */
    public const ALL = [
        '21-9' => '21:9 — панорама',
        '16-9' => '16:9 — широкий кадр',
        '4-3' => '4:3 — классический',
        '1-1' => '1:1 — квадрат',
        '4-5' => '4:5 — вертикальный',
        '9-16' => '9:16 — вертикальный, как сторис',
        'auto' => 'Как у изображения',
    ];

    public static function normalize(mixed $value): string
    {
        $value = is_string($value) ? trim($value) : '';

        return isset(self::ALL[$value]) ? $value : self::DEFAULT;
    }

    /** @return array<int, string> */
    public static function keys(): array
    {
        return array_keys(self::ALL);
    }
}
