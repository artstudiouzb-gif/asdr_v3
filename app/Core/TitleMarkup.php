<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Разметка внутри строки заголовка: выделение слова звёздочками
 * («Стратегия *развития* региона») и принудительный перенос строки вертикальной
 * чертой («Агентство стратегического | развития и реформ»).
 *
 * Приём выбран вместо отдельной колонки «какие слова красить» намеренно:
 * колонка хранила бы номера слов и разъезжалась с текстом при первой же
 * правке заголовка, да ещё и отдельно на каждом языке. Разметка живёт внутри
 * самой строки — переводчик переносит звёздочки туда, где в его языке стоит
 * нужное слово, и ничего синхронизировать не нужно.
 *
 * Заголовок остаётся простым текстом: HTML внутрь не допускается, звёздочки
 * разбираются УЖЕ ПОСЛЕ экранирования. Поэтому `<b>` в заголовке по-прежнему
 * виден как текст, а не как разметка, и правило «поля-заголовки не принимают
 * HTML» не нарушено.
 *
 * Перенос сделан чертой, а не тегом `<br>`: тег в заголовке экранируется и
 * виден как текст — правило «поля-заголовки не принимают HTML» важнее удобства
 * записи. Черта же разбирается уже после экранирования, как и звёздочки, и
 * приехать из самого текста не может. Символ выбран за то, что в заголовке
 * госсайта он не встречается: слэш бывает в «24/7» и в адресах, дефис и тире —
 * в обычной пунктуации.
 *
 * Где HTML недопустим (title=, alt=, <title>, meta, пост в Telegram, поисковый
 * индекс) — зовите plain(): она снимает разметку, ничего не добавляя.
 */
final class TitleMarkup
{
    /**
     * Пара звёздочек вокруг непустого куска строки без переноса.
     *
     * Пробел сразу после открывающей (и перед закрывающей) не считается
     * разметкой: в тексте «5 * 3 = 15 * 5» звёздочки — знак умножения, и
     * красить середину выражения нельзя. Ограничение длины отсекает случай,
     * когда одинокая звёздочка в начале строки «съедает» весь заголовок до
     * следующей.
     */
    private const PATTERN = '/\*(?!\s)([^*\n]{1,200}?)(?<!\s)\*/u';

    /**
     * Черта переноса вместе с пробелами вокруг: «слово | слово» и «слово|слово»
     * дают одинаковый результат, а «слово || слово» — один перенос, а не два.
     * Редактор ставит черту там, где ему удобно её видеть, а не там, где она
     * нужна разбору.
     */
    private const BREAK_PATTERN = '/\s*\|+\s*/u';

    /** Экранированный заголовок: *слово* — акцентный span, | — перенос строки. */
    public static function html(?string $text): string
    {
        $escaped = htmlspecialchars((string) $text, ENT_QUOTES);

        // Экранирование ни звёздочек, ни черты не производит, поэтому разбор
        // безопасен: разметка не может приехать из самого текста.
        $marked = (string) preg_replace(
            self::PATTERN,
            '<span class="tx-mark">$1</span>',
            $escaped
        );

        // Голый <br> без класса: правила для него нет и не нужно, а класс без
        // правила годами читается как рабочий приём.
        $withBreaks = (string) preg_replace(self::BREAK_PATTERN, '<br>', $marked);

        // Черта с краю переносить нечего: пустая строка сверху или снизу
        // читалась бы как лишний отступ, а не как замысел редактора.
        return trim((string) preg_replace('/^(?:<br>)+|(?:<br>)+$/u', '', $withBreaks));
    }

    /** Тот же заголовок без разметки — для атрибутов, SEO и поиска. */
    public static function plain(?string $text): string
    {
        $plain = (string) preg_replace(self::PATTERN, '$1', (string) $text);

        // Перенос становится пробелом: в одну строку заголовок читается так же,
        // как в две, а склейка «АгентствоРазвития» — уже другое слово.
        return trim((string) preg_replace(self::BREAK_PATTERN, ' ', $plain));
    }

    /** Есть ли в строке принудительный перенос (нужно шаблонам без разметки). */
    public static function hasBreak(?string $text): bool
    {
        return str_contains((string) $text, '|');
    }

    /** Есть ли в строке выделение (нужно шаблонам, решающим, звать ли html()). */
    public static function has(?string $text): bool
    {
        return preg_match(self::PATTERN, (string) $text) === 1;
    }
}
