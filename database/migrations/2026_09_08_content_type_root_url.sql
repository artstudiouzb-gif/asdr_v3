-- Адрес типа контента без префикса /catalog.
--
-- Каталоги живут на `/catalog/<slug>`, и это честная структура: по адресу
-- видно, что открыт раздел каталога, а слаг типа не спорит с адресами
-- страниц. Но для раздела вроде «Документы» префикс лишний — его печатают на
-- бланках и произносят вслух.
--
-- Флаг выключен по умолчанию: у работающего сайта адреса не меняются, пока
-- редактор сам не попросит. Столкновение с адресом страницы проверяется при
-- сохранении типа (ContentType::rootUrlConflict) — иначе тип молча перекрыл бы
-- страницу с тем же слагом.
ALTER TABLE content_types
    ADD COLUMN root_url TINYINT(1) NOT NULL DEFAULT 0 AFTER is_public;
