-- @post-schema
-- «Карточки персон» и «Профиль персоны» больше не типы блока.
--
-- Людей на сайте выводят два блока: «Команда» (`team_list`) берёт состав из
-- одноимённого раздела, а «Карточка руководителя» (`leader_card`) показывает
-- одного человека с вкладками. Эти два повторяли их вручную набранным
-- списком и профилем без вкладок — и расходились с ними при первой правке.
--
-- Данные не переносятся: страницы руководства владелец собирает в админке
-- заново. Строки удаляем, а не оставляем: типа больше нет, и такой блок
-- выходит комментарием «Неизвестный тип блока» — в редакторе он читается как
-- поломка, а на странице молча ничего не печатает.
DELETE FROM blocks WHERE type IN ('person_cards', 'person_profile');

