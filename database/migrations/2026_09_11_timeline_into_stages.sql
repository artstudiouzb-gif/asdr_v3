-- @post-schema
-- «Хронология» и «Этапы» — один тип блока.
--
-- Оба показывали события во времени, и оба подписывались в списке добавления
-- словом «таймлайн»: выбрать между ними по описанию было нельзя, а правка
-- одного молча расходилась со вторым. Различала их раскладка — лента карточек
-- против вертикального списка, — и она стала настройкой `layout`.
--
-- Данные не перекладываются: поля элемента у «Этапов» это надмножество полей
-- «Хронологии» (год, описание, статус), поэтому старые события читаются как
-- есть. Переезжает только шапка: кнопка под списком («Вся история») — это та
-- же ссылка «Все …», что у ленты, и второго поля для неё не нужно.
--
-- `blocks.data` объявлена типом JSON, то есть невалидного значения там быть не
-- может, и JSON_SET не вернёт NULL поверх содержимого блока.
UPDATE blocks
   SET type = 'stages',
       data = JSON_SET(
           data,
           '$.layout', 'list',
           '$.all_text', COALESCE(JSON_UNQUOTE(JSON_EXTRACT(data, '$.button_text')), ''),
           '$.all_url',  COALESCE(JSON_UNQUOTE(JSON_EXTRACT(data, '$.button_url')), '')
       )
 WHERE type = 'timeline';

-- Шаблоны страниц (библиотека сниппетов) хранят те же блоки отдельным JSON.
-- Без этого шага сохранённый шаблон при следующем применении положил бы на
-- страницу блок несуществующего типа.
UPDATE block_snippets
   SET blocks_json = REPLACE(blocks_json, '"type":"timeline"', '"type":"stages"')
 WHERE blocks_json LIKE '%"type":"timeline"%';
