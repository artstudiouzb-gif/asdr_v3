-- Язык можно скрыть с сайта, оставив его в админке: переводы готовят заранее,
-- а посетитель видит язык только после открытия. Супер-админ видит скрытый
-- язык и на сайте — чтобы проверить переводы до публикации.
ALTER TABLE languages
    ADD COLUMN is_public TINYINT(1) NOT NULL DEFAULT 1 COMMENT 'показывать на сайте (0 — только админка и супер-админ)' AFTER is_active;
