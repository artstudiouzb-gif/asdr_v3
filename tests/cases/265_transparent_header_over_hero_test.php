<?php

declare(strict_types=1);

/*
 * Прозрачная шапка над обложкой. Светлый набор шапки — белое лого, белое меню,
 * белые иконки — читается только на тёмном кадре, а картинку слайда выбирает
 * редактор. Две страховки, и обе ломаются молча: вёрстка остаётся «нормальной
 * на вид», просто лого исчезает на светлом слайде.
 */

test('Под прозрачной шапкой лежит затемняющая подложка', function () {
    $theme = theme_css();

    // Голый `background: transparent` возвращает исходную поломку: на светлой
    // фотографии белое лого и меню не видно вовсе. Подложка не зависит от
    // схемы слайда — схема описывает заливку, а не яркость верхней полосы.
    $rule = (string) preg_replace(
        '/^.*?body \.site-header--transparent:not\(\.is-scrolled\) \{(.*?)\}.*$/s',
        '$1',
        $theme
    );
    assert_contains('linear-gradient', $rule, 'подложка под шапкой снята — на светлом кадре шапка пропадёт');
    assert_contains('--hdr-scrim', $rule, 'плотность подложки должна управляться переменной');

    // Верхняя полоса — часть той же поверхности: без своей подложки она
    // осталась бы белым текстом на светлом кадре.
    $topbar = (string) preg_replace(
        '/^.*?body:has\(\.site-header--transparent\) \.site-topbar \{(.*?)\}.*$/s',
        '$1',
        $theme
    );
    assert_contains('--hdr-scrim', $topbar, 'у верхней полосы нет подложки');
});

test('На светлом слайде шапка переключается на тёмный набор', function () {
    $theme = theme_css();

    // Цвет светлого набора обязан идти через переменную: жёсткий #fff в
    // правилах не переключить, и весь приём осыпается.
    assert_contains('var(--hdr-fg, #fff)', $theme, 'цвета шапки перестали идти через --hdr-fg');

    $rule = (string) preg_replace(
        '/^.*?body\.is-hero-light \.site-header--transparent:not\(\.is-scrolled\),(.*?)\}.*$/s',
        '$1',
        $theme
    );
    assert_contains('--hdr-scrim: 0', $rule, 'на светлом кадре подложка должна сниматься');
    assert_contains('--hdr-fg', $rule, 'на светлом кадре нужен тёмный цвет шапки');
    assert_contains('--menu-color-transparent', $rule, 'меню останется белым на светлом кадре');

    // Переменные темы здесь нельзя: кадр слайда одинаков в обеих темах, а
    // --gov-title в тёмной переворачивается в белый и вернёт ту же проблему.
    assert_not_contains('--gov-title', $rule, 'цвет светлого режима взят из переменной темы');
    // Акцент настраивается в «Дизайне», поэтому оттенок наведения только
    // затемняется от него, а не задаётся фиксированным цветом.
    assert_contains('color-mix', $rule, 'оттенок наведения должен считаться от акцента');

    // Переключается весь набор, а не логотип: иконки, бургер, поле поиска и
    // границы держались на белом литерале и оставались белыми на светлом кадре.
    $frontend = (string) file_get_contents(APP_ROOT . '/public/assets/css/frontend.css');
    foreach (['--hdr-veil', '--hdr-ink-shadow'] as $token) {
        assert_contains($token, $theme, 'переменная ' . $token . ' пропала из темы');
    }
    assert_contains('var(--hdr-fg, #fff) !important', $frontend, 'иконки шапки снова красятся белым литералом');

    // Логотип возвращается к обычному варианту — иначе светлый останется.
    assert_contains(
        'body.is-hero-light .site-header--transparent:not(.is-scrolled) .site-header__logo-light',
        $theme,
        'на светлом кадре светлое лого не переключается на обычное'
    );
});

test('Набор шапки меняется в середине перехода, а не по клику', function () {
    $js = (string) file_get_contents(APP_ROOT . '/public/assets/js/blocks/hero.js');
    $theme = theme_css();

    // Кадр проявляется за время перехода, а класс менялся сразу: замерено —
    // через 30 мс новый кадр виден на 1 %, и тёмный логотип треть секунды
    // лежал на ещё не ушедшем тёмном кадре.
    assert_contains('headerTimer', $js, 'смена набора снова происходит сразу по клику');
    assert_contains('duration || 0) / 2', $js, 'смена набора не приходится на середину перехода');
    assert_contains('reduceMotion()', $js, 'при «меньше движения» задержки быть не должно');

    // Подложка гаснет вместе с переходом: обычные переменные не
    // анимируются, поэтому её плотность объявлена через @property.
    assert_contains('@property --hdr-scrim', $theme, 'плотность подложки снова неанимируема');
    assert_contains('transition-property: --hdr-scrim', $theme, 'подложка исчезает скачком');
});

test('Обложка сообщает шапке схему кадра, а не цвет своего текста', function () {
    $renderer = (string) file_get_contents(APP_ROOT . '/app/Core/Hero/HeroRenderer.php');
    $js = (string) file_get_contents(APP_ROOT . '/public/assets/js/blocks/hero.js');

    // Признак считает сервер и кладёт в атрибут слайда.
    assert_contains('data-hero-scheme=', $renderer, 'слайд перестал сообщать схему кадра');
    assert_contains('data-hero-scheme', $js, 'скрипт читает не тот признак');
    assert_contains('is-hero-light', $js, 'скрипт не ставит класс на body');
    assert_contains('site-header--transparent', $js, 'скрипт трогает шапку и без прозрачного режима');
    // Шапка лежит поверх первого блока страницы: обложка ниже по странице
    // под ней не лежит, и её кадр к шапке отношения не имеет.
    assert_contains('cms-block', $js, 'скрипт следит за обложкой, которая не под шапкой');

    // Синхронизация нужна при первом показе, у обложки из одного слайда и при
    // смене — иначе первый экран уедет со старым набором.
    assert_true(
        substr_count($js, 'syncHeaderToSlide(') >= 4,
        'синхронизация должна вызываться при инициализации, на одиночном слайде и при смене'
    );

    // Под фотографией и видео яркость верхней полосы не известна никому:
    // «светлая схема» на снимке ночного города переключила бы шапку в тёмное
    // по тёмному. Такие слайды обязаны оставаться тёмными для шапки.
    $rule = (string) preg_replace(
        '/^.*?private static function headerScheme\(array \$d, array \$s\): string\s*\{(.*?)\n    \}.*$/s',
        '$1',
        $renderer
    );
    assert_contains("media_type", $rule, 'признак перестал различать медиа-фон');
    assert_contains("'dark'", $rule, 'медиа-слайд обязан оставаться тёмным для шапки');
    // Заливку задаёт обложка целиком: у слайда своей схемы нет. Признак
    // кадра считается тем же способом, что и сам фон, иначе шапка начнёт
    // врать про то, на чём она лежит.
    assert_contains('schemeIsDark($s)', $rule, 'признак и фон считаются по-разному');
});
