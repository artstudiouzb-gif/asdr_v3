<?php

declare(strict_types=1);

/*
 * Долг статического анализа: бюджет, который может только уменьшаться.
 *
 * Планка поднята до 7-го уровня, но привести к нему весь существующий код
 * разом нельзя: 633 из находок — это требование описать типы значений массивов
 * в сотнях докблоков. Поэтому текущие находки заморожены в эталоне
 * (`phpstan-baseline.neon`), и это осознанный компромисс, а не решение:
 *
 *  - **новый код проверяется целиком** на 7-м уровне, то есть следующая порция
 *    таких же дефектов не появится;
 *  - **старый долг посчитан и виден**, а не растворён в понижении планки.
 *
 * Тест держит бюджет тем же приёмом, что бюджет `!important` в CSS и бюджет
 * классов без правил: число в эталоне разрешено только уменьшать. Выросло —
 * значит, в эталон дописали новую находку вместо того, чтобы её починить.
 */

test('Эталон PHPStan не растёт', function () {
    // Потолок и подсчёт объявлены в tests/budgets.php вместе с остальными
    // бюджетами проекта: каждая запись эталона несёт `count: N`, считаем
    // находки, а не строки.
    assert_true(is_file(APP_ROOT . '/phpstan-baseline.neon'), 'эталон PHPStan не найден');

    $budget = quality_budget('phpstan_baseline');
    assert_true(
        $budget['value'] !== null && $budget['value'] > 0,
        'в эталоне не разобрано ни одной записи'
    );

    // Планка. Уменьшать — можно и нужно; увеличивать — нет.
    assert_true(
        $budget['value'] <= $budget['ceiling'],
        'находок в эталоне не больше ' . $budget['ceiling'] . ' (сейчас ' . $budget['value'] . ', '
            . $budget['detail'] . '). Новую находку надо чинить, а не дописывать в эталон.'
    );
});

test('Уровень анализа не понижен', function () {
    $config = str_replace("\r\n", "\n", (string) file_get_contents(APP_ROOT . '/phpstan.neon'));

    assert_true(
        (bool) preg_match('/^\s*level:\s*(\d+)$/m', $config, $m) && (int) $m[1] >= 7,
        'уровень PHPStan опущен ниже седьмого'
    );
    // Эталон обязан подключаться: без него уровень объявлен, но не действует.
    assert_contains('phpstan-baseline.neon', $config, 'эталон не подключён к конфигу');
});
