<?php

declare(strict_types=1);

/*
 * Логотип шапки: бокс задан настройкой, картинка прижата к краю.
 *
 * Ширина и высота логотипа приходят из конструктора шапки, поэтому <img>
 * получает фиксированный бокс, а не размер картинки. `object-fit: contain`
 * вписывает снимок в этот бокс и по умолчанию центрирует остаток — при
 * настройке «Слева» логотип всё равно стоял с отступом в десятки пикселей.
 */
test('Логотип шапки прижат к краю бокса, а по центру — только по настройке', function () {
    $css = (string) file_get_contents(APP_ROOT . '/public/assets/css/frontend.css');

    assert_contains(
        'object-position: left center;',
        $css,
        'картинка логотипа обязана прижиматься к началу строки, иначе contain центрирует её в боксе'
    );
    assert_contains(
        '.site-header--logo-center .site-header__logo img { object-position: center; }',
        $css,
        'выбор «По центру» в конструкторе шапки должен центрировать и картинку внутри бокса'
    );
});
