<?php

declare(strict_types=1);

use App\Core\Updater;

/*
 * Репозиторий обновлений не настраивается в панели — и это решение, а не
 * недоделка: поле в админке позволило бы редактору увести обновление на чужой
 * репозиторий, то есть выполнить свой код на сервере. Адрес приходит из
 * окружения (`UPDATE_REPO`), а в коде лежит только умолчание.
 *
 * Но умолчание, записанное однажды, устаревает молча: репозиторий переехал с
 * `asdr_v2` на `asdr_v3`, а панель продолжала называть старый адрес — и
 * назвала бы его же при обновлении, то есть искала бы релизы там, где их
 * больше не выпускают. Отказ тихий: релизов «нет», хотя они есть.
 *
 * Поэтому умолчание сверяется с тем репозиторием, в котором лежит сам код.
 */

test('Умолчание репозитория обновлений совпадает с этим репозиторием', function (): void {
    $remote = @shell_exec('git -C ' . escapeshellarg(APP_ROOT) . ' remote get-url origin 2>/dev/null');
    $remote = is_string($remote) ? trim($remote) : '';
    if ($remote === '') {
        skip_test('git-remote недоступен — сверять умолчание не с чем');
        return;
    }
    if (preg_match('#[:/]([A-Za-z0-9._-]+/[A-Za-z0-9._-]+?)(?:\.git)?$#', $remote, $m) !== 1) {
        skip_test('адрес origin не разобран: ' . $remote);
        return;
    }

    // Переменная окружения главнее умолчания, поэтому на время проверки её
    // снимаем: иначе тест мерил бы окружение раннера, а не то, что записано в
    // коде и достанется сайту без этой переменной.
    $saved = getenv('UPDATE_REPO');
    putenv('UPDATE_REPO');
    $default = Updater::repo();
    if (is_string($saved)) {
        putenv('UPDATE_REPO=' . $saved);
    }

    assert_same(
        $m[1],
        $default,
        'умолчание указывает на другой репозиторий: обновление искало бы релизы там, где их не выпускают'
    );
});

test('Путь с лишними сегментами репозиторием не считается', function (): void {
    // Значение уходит в URL запроса к GitHub, поэтому форма проверяется: без
    // проверки «../» и путь с лишними сегментами увели бы запрос не туда.
    // Что окружение вообще главнее умолчания, проверяет тест 291.
    $saved = getenv('UPDATE_REPO');

    putenv('UPDATE_REPO=../../evil');
    assert_true(Updater::repo() !== '../../evil', 'негодная форма отбрасывается');
    putenv('UPDATE_REPO=owner/repo/extra');
    assert_true(Updater::repo() !== 'owner/repo/extra', 'третий сегмент — не репозиторий');

    if (is_string($saved)) {
        putenv('UPDATE_REPO=' . $saved);
    } else {
        putenv('UPDATE_REPO');
    }
});
