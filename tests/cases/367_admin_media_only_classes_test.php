<?php

declare(strict_types=1);

/*
 * Класс, у которого правила есть только внутри `@media`.
 *
 * Сторож мёртвых классов (тест 278) такой случай пропускает: правило у класса
 * есть, значит формально он живой. А работает только его половина.
 *
 * Так жил `.form-grid-2col`. В редакторе блока он объявлял сетку в две колонки
 * для пар полей «градиент от / до» и «цвет узора + размер». В CSS у него было
 * ровно одно правило — внутри `@media (max-width: 860px)`, то есть «схлопни в
 * одну колонку». Самой сетки не существовало нигде: поля годами стояли друг
 * под другом, хотя разметка заявляла обратное, и никакой сторож этого не видел.
 *
 * Отличить забытую базу от условного класса автоматически нельзя: `display:
 * none` на узком экране — законный класс, у которого видимое состояние и есть
 * умолчание.
 *
 * Поэтому храповика здесь нет, и это осознанно. Остальные бюджеты проекта
 * считают дефекты — лишний `!important`, класс без правил, находку PHPStan, —
 * и добавлять их незачем никогда. Этот считает **приём, который бывает
 * законным**, и потолок «по факту» превратился бы в ловушку: следующий честный
 * класс уронил бы тест, а поднять потолок правила проекта не позволяют.
 *
 * Вместо потолка — список объяснённых случаев (`ADMIN_MEDIA_ONLY_BY_DESIGN`) с
 * причиной у каждого, а бюджет считает необъяснённые, и его потолок ноль. Цена
 * входа в список — одна строка с обоснованием: это дешевле молчаливого запаса
 * и честнее, чем «нам можно ещё четыре».
 */

test('Необъяснённых классов только внутри @media нет', function (): void {
    $budget = quality_budget('admin_media_only_classes');

    assert_true(
        $budget['value'] <= $budget['ceiling'],
        'у класса с правилом только внутри @media должно быть объяснение в '
            . 'ADMIN_MEDIA_ONLY_BY_DESIGN — либо забытое базовое правило '
            . '(сейчас без объяснения: ' . $budget['value'] . ' — ' . $budget['detail'] . ')'
    );
});

test('Объяснение требуется настоящее, а не пустая строка', function (): void {
    // Список с пустыми причинами — то же молчаливое согласие, только длиннее.
    assert_true(ADMIN_MEDIA_ONLY_BY_DESIGN !== [], 'разобранные случаи перечислены');
    foreach (ADMIN_MEDIA_ONLY_BY_DESIGN as $class => $why) {
        assert_true(mb_strlen(trim($why)) >= 20, 'у класса ' . $class . ' причина не написана');
    }

    // И список не должен обрастать именами, которых в CSS уже нет: тогда он
    // начнёт молча оправдывать несуществующее.
    $actual = array_flip(admin_media_only_classes());
    foreach (array_keys(ADMIN_MEDIA_ONLY_BY_DESIGN) as $class) {
        assert_true(
            isset($actual[$class]),
            'класс ' . $class . ' уже не из этого случая — уберите его из списка объяснений'
        );
    }
});

test('Мера ловит именно забытую базу, а не любой класс из медиазапроса', function (): void {
    // Проверяем сам приём измерения: без этого бюджет мог бы считать что
    // угодно и держать потолок над бессмысленным числом.
    $classes = admin_media_only_classes();

    // `.form-grid-2col` починен — базовое правило у него теперь есть, и в
    // списке его быть не должно. Это и есть доказательство, что мера видит
    // ровно тот дефект, ради которого заведена.
    assert_false(
        in_array('form-grid-2col', $classes, true),
        'починенный класс не должен числиться сломанным'
    );

    // А класс с правилом только в медиазапросе — должен.
    assert_true(
        in_array('admin-tools__quick', $classes, true),
        'класс, у которого правило есть только внутри @media, обязан попадать в счёт'
    );
});
