<?php

declare(strict_types=1);

/*
 * Фотографии детальной страницы новости. Мест вывода несколько, и относиться
 * к ним одинаково нельзя: у первого экрана и у того, до чего нужно долистать,
 * задачи прямо противоположные.
 */

test('Главный кадр галереи получает высокий приоритет, остальные слайды — нет', function () {
    // Первый слайд — самый крупный элемент первого экрана, то есть LCP
    // страницы. Не ленивым он был и раньше, но высокого приоритета не получал:
    // браузер ставил его в общую очередь наравне с миниатюрами галереи и
    // кадрами соседних новостей.
    $view = (string) file_get_contents(APP_ROOT . '/app/Views/site/news_show.php');

    assert_contains(
        "'(max-width: 900px) 100vw, 70vw', \$i === 0",
        $view,
        'приоритет адресован ровно первому слайду'
    );
    // Ленивость по-прежнему считается от того же номера: первый кадр eager,
    // остальные ленивые — их не видно до листания.
    assert_contains("\$i !== 0, '(max-width: 900px) 100vw, 70vw'", $view, 'ленивы все слайды, кроме первого');

    // Обложка видео — тот же первый экран, но идёт мимо Media::picture
    // (у неё свой откат на кадр YouTube через data-fallback в news.js).
    assert_contains('loading="eager" fetchpriority="high"', $view, 'обложка видео тоже первый экран');
});

test('Первый экран детальной страницы не проявляется, а нижние фотографии — проявляются', function () {
    $js = (string) file_get_contents(APP_ROOT . '/public/assets/js/frontend.js');

    $start = strpos($js, 'var SOFT_MEDIA = [');
    assert_true($start !== false, 'список мест объявлен один раз');
    $list = substr($js, (int) $start, (int) strpos($js, '].join(', (int) $start) - (int) $start);

    // Сетка фотографий и боковая галерея стоят ниже первого экрана: до них
    // листают, и там проявление кадра уместно.
    assert_contains("'.newsdetail-photos__item img'", $list, 'сетка фотографий проявляется');
    assert_contains("'.newsdetail-sidegallery__item img'", $list, 'боковая галерея проявляется');

    // А главный слайд — нет, и причин две. Спрятав LCP ради плавности, мы
    // задержали бы то, ради чего страницу открыли (то же правило, по которому
    // первый блок страницы не получает появления при скролле). И у слайдов уже
    // СВОЯ механика прозрачности — переключение классом `is-active`, — так что
    // второй механизм на том же свойстве спорил бы с ней.
    assert_true(!str_contains($list, 'newsdetail-gallery__slide'), 'LCP-кадр не прячется ради проявления');
    assert_true(!str_contains($list, 'news-video__thumb'), 'обложка видео не прячется');

    $css = (string) file_get_contents(APP_ROOT . '/public/assets/css/blocks/news-detail.css');
    assert_contains('.newsdetail-gallery__slide.is-active', $css, 'у слайдов своя механика прозрачности');

    // Второй копии перехода в стилях детальной страницы быть не должно:
    // правило в теме висит на классе и мест не знает.
    assert_true(
        !str_contains($css, 'is-media-loading'),
        'приём объявлен один раз в теме, а не продублирован в стилях страницы'
    );
});
