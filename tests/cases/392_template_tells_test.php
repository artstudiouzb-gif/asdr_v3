<?php

declare(strict_types=1);

/*
 * Признаки шаблона — бюджеты, которые могут только уменьшаться.
 *
 * Навык frontend-design перечисляет приёмы, по которым страница читается
 * сгенерированной: метка капслоком над заголовком, «→» в конце ссылки,
 * мета-строка через « · ». Часть из них законна (стрелка листания страниц,
 * аббревиатура), поэтому запрета нет — есть храповик: новые не появляются
 * молча, а чистка видна числом (DESIGN_PLAN, очередь 4). Потолки и замер
 * объявлены в tests/budgets.php, отчёт — `quality-budgets`.
 */

foreach (['tell_uppercase', 'tell_arrows', 'tell_middots'] as $id) {
    test('Признак шаблона не растёт: ' . $id, function () use ($id): void {
        $budget = quality_budget($id);
        assert_true(
            $budget['value'] <= $budget['ceiling'],
            sprintf(
                '%s: %d при потолке %d (%s). Уберите новое или объясните, почему оно не шаблон — '
                . 'подпись выделяется весом и цветом, а стрелка нужна только направлению.',
                $budget['title'],
                $budget['value'],
                $budget['ceiling'],
                $budget['detail']
            )
        );
    });
}

test('Признаки шаблона не считают комментарии', function (): void {
    // «Было → стало» в комментарии — не вывод. Если разбор перестанет
    // вырезать комментарии, бюджет начнёт штрафовать объяснения.
    $sources = template_tell_sources();
    assert_true($sources !== [], 'исходники нашлись');
    foreach ($sources as $path => $code) {
        assert_not_contains('/*', $code, "$path: комментарий попал в замер");
    }
});
